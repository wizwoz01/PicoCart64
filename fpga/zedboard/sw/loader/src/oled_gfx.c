void gfx_clear(uint8_t *fb)
{
	memset(fb, 0, GFX_FB_SIZE);
}

void gfx_fill(uint8_t *fb, int row, int x0, int x1, uint8_t bits)
{
	if (row < 0 || row >= GFX_ROWS)
		return;
	if (x0 < 0)
		x0 = 0;
	if (x1 > GFX_W)
		x1 = GFX_W;
	for (; x0 < x1; x0++)
		fb[row * GFX_W + x0] = bits;
}

int gfx_textn(uint8_t *fb, int row, int x, const char *s, int n, int inv)
{
	uint8_t *line = fb + row * GFX_W;
	uint8_t mask = inv ? 0xFF : 0x00;
	int i;

	if (row < 0 || row >= GFX_ROWS)
		return x;
	for (; *s && n > 0; s++, n--) {
		unsigned char c = (unsigned char)*s;
		const uint8_t *g = font5x7[(c >= 0x20 && c < 0x7F) ? c - 0x20 : '?' - 0x20];

		for (i = 0; i < GFX_CHAR_W; i++, x++) {
			if (x < 0)
				continue;
			if (x >= GFX_W)
				return x;
			line[x] = (i < 5 ? g[i] : 0) ^ mask;
		}
	}
	return x;
}

int gfx_text(uint8_t *fb, int row, int x, const char *s, int inv)
{
	return gfx_textn(fb, row, x, s, GFX_W, inv);
}

void gfx_vline(uint8_t *fb, int x, int y0, int y1)
{
	if (x < 0 || x >= GFX_W)
		return;
	if (y0 < 0)
		y0 = 0;
	if (y1 > GFX_H)
		y1 = GFX_H;
	for (; y0 < y1; y0++)
		fb[(y0 >> 3) * GFX_W + x] |= (uint8_t)(1u << (y0 & 7));
}

void gfx_progress(uint8_t *fb, int row, uint32_t num, uint32_t den)
{
	const int x0 = 2, x1 = GFX_W - 2;
	int fill = x0, x;

	if (den != 0) {
		if (num > den)
			num = den;
		fill = x0 + (int)((uint64_t)(x1 - x0) * num / den);
	}
	gfx_fill(fb, row, 0, GFX_W, 0);
	for (x = x0; x < x1; x++)
		fb[row * GFX_W + x] = (x == x0 || x == x1 - 1 || x < fill) ? 0x7E : 0x42;
}
